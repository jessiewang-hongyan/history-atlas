"""Publish biographies with separate, source-linked geographical reviews."""
import json
import math
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.loads((ROOT/'research/people/initial-review.json').read_text())
geo=json.loads((ROOT/'research/people/map-review.json').read_text())
d['geography']=geo
# Only established regional reference coordinates are reused, never invented from an event's place text.
points={'长安':[108.94,34.26],'江阴':[120.28,31.92],'天台山一带':[121.03,29.15],'鸡足山':[100.37,25.96],'汴京':[114.31,34.8],'北京':[116.4,39.9],'东京':[139.69,35.68],'上海':[121.47,31.23],'绍兴':[120.58,30],'绍兴大通学堂':[120.58,30],'绍兴轩亭口':[120.58,30]}
# Record-level opt-in: no event locations, contested arrival dates, or unsupported birthplaces.
allowed={'xuanzang':{'xuanzang-003','xuanzang-005','xuanzang-008','xuanzang-014'},'xuxiake':{'xuxiake-001','xuxiake-003','xuxiake-008','xuxiake-010','xuxiake-011','xuxiake-012'},'liqingzhao':{'liqingzhao-002'},'qinliangyu':{'qinliangyu-007'},'qiujin':{'qiujin-002','qiujin-003','qiujin-005','qiujin-007','qiujin-008','qiujin-012'}}
record_ids={r['id'] for p in d['people'] for r in p['records']}
assert set(geo['records']).issubset(record_ids)
assert set(geo['withheld']).issubset(record_ids)
assert not set(geo['records']).intersection(geo['withheld'])
for p in d['people']:
 for r in p['records']:
  place='长安' if r['place'].startswith('长安') else r['place']
  r['displayXY']=points.get(place) if r['id'] in allowed[p['id']] else None
  r['locationReview']=None
  r['displayArea']=None
  review=geo['records'].get(r['id'])
  if review:
   location=geo['places'][review['placeId']]
   r['displayXY']=location['xy']
   r['locationReview']={**review,**location}
  if review:
   km=2 if any(t in location['precision'] for t in ['寺','遗址','废址','景观','岩洞']) else 40 if '山域' in location['precision'] else 20
   lon,lat=location['xy'];dx=km/(111*math.cos(math.radians(lat)));dy=km/111
   r['displayArea']={'name':location['name'],'bounds':[lon-dx,lat-dy,lon+dx,lat+dy],'note':geo['areaPolicy']}
  area=geo.get('areas',{}).get(r['id'])
  if area:
   assert not review and not r['displayXY']
   r['displayArea']={'name':area['name'],'bounds':area['bounds'],'note':area['notes']}
   r['locationReview']=area
  if r['id'] in geo['withheld']:
   assert not r['displayXY'], 'Withheld location cannot be mapped: '+r['id']
  r['mapNote']='地图标记沿用原型的城市或区域近似位置，尚未校准历史城址。' if r['displayXY'] else geo['withheld'].get(r['id'],'这条经历暂不标地图位置。')
  if review:
   r['mapNote']='地图用淡色圈出'+location['name']+'的大致方位，圈线不是活动边界。'+location['notes']
  if area:r['mapNote']=area['notes']
output=('// Generated by scripts/build_lives.py; research coordinates remain unchanged.\nconst LIVES_RESEARCH = '+json.dumps(d,ensure_ascii=False,separators=(',',':'))+';\n'+'''for(const life of LIVES_RESEARCH.people){
 const p=PEOPLE.find(p=>p.id===life.id);
 p.lifeResearch=life;p.audited=true;
 p.nodes=life.records.map(r=>({...r,xy:r.displayXY,area:r.displayArea,text:r.narrative||r.evidence[0].supports,date:r.dateLabel,note:[r.dateLabel,r.limits,r.mapNote].filter(Boolean).join(' · ')}));
 p.caveat='每条经历都附有出处。日期有分歧的地方保留原说；地图只标出部分有到访依据的区域。';
}
''')
target=ROOT/'dist/lives-data.js'
if '--check' in sys.argv:
 assert target.read_text()==output, 'Run python3 scripts/build_lives.py to update website data'
else:
 target.write_text(output)
# Ship only the selected biography and the references it actually cites.
import hashlib
out_dir=ROOT/'dist'/'people'
if '--check' not in sys.argv:out_dir.mkdir(exist_ok=True)
manifest={}
def asset(path,content):
 if '--check' in sys.argv:assert path.read_text()==content, f'Stale asset: {path}'
 else:path.write_text(content)
for life in d['people']:
 refs={e['source'] for r in life['records']+life['episodes'] for e in r['evidence']}
 geography={sid for r in life['records'] if r['locationReview'] for sid in r['locationReview']['sources']}
 payload=json.dumps({'life':life,'sources':{k:d['sources'][k] for k in sorted(refs)},'geoSources':{k:geo['sources'][k] for k in sorted(geography)}},ensure_ascii=False,separators=(',',':'))
 name=life['id']+'.json'
 asset(out_dir/name,payload)
 manifest[life['id']]='people/'+name+'?v='+hashlib.sha256(payload.encode()).hexdigest()[:10]
asset(ROOT/'dist'/'life-files.js','const LIFE_FILES='+json.dumps(manifest,separators=(',',':'))+';\n')
print('Published',sum(len(p['records']) for p in d['people']),'records and',sum(len(p['episodes']) for p in d['people']),'episodes;',sum(bool(r['displayXY']) for p in d['people'] for r in p['records']),'regional markers')

total=sum(len(p['records']) for p in d['people'])
episodes=sum(len(p['episodes']) for p in d['people'])
markers=sum(bool(r['displayXY']) for p in d['people'] for r in p['records'])
reviewed=len(geo['records'])
area_only=len(geo.get('areas',{}))
lines=['# 五人地图位置核验 · '+geo['checkedAt'],'',f'目前共{total}条年度索引经历、{episodes}段未定年经历；{markers}条年度记录带地图位置。其中{reviewed}条附独立地理核验，{markers-reviewed}条仍沿用原型城市或区域近似点。另有{area_only}条仅知地区的经历用区域阴影展示；其余{total-markers-area_only}条年度经历只展示文字。','',geo['coordinatePolicy'],'',geo['areaPolicy'],'','同一地点多次到访，仍分别算作人生记录。地名能定位不等于人物到访日期已经确定；来源与条件逐条保留。','', 'DILA新增地名的摘录、版本与许可见 [geography-extract.json](geography-extract.json)。摘录及其改编按 CC BY-SA 3.0 提供；来源数据库为法鼓文理学院。', '', '## 已核区域记录','']
for person in d['people']:
 lines += ['### '+person['name'],'']
 for r in person['records']:
  g=r.get('locationReview')
  if not g:continue
  lines += [f"- **{r['id']} · {r['year']} · {r['title']}**：{g['name']}（{g['precision']}；经度、纬度 {g.get('xy','仅示意范围')}）。",'  '+g['presenceBasis'],'  '+g['notes'],'  到访依据：'+ '；'.join(f"[{d['sources'][e['source']]['title']}]({d['sources'][e['source']]['url']}) · {e['locator']}" for e in r['evidence']),'  地理依据：'+'；'.join(f"[{geo['sources'][sid]['title']}]({geo['sources'][sid]['url']})" for sid in g['sources']),'']
lines += ['## 继续保留文字的记录','','这里只列本轮重点检查的限制；其余未列入本轮定位清单的经历沿用原有待核状态。','']
lines += [f'- {id}：{reason}' for id,reason in geo['withheld'].items()]
lines += ['','## 地理资料与使用范围','']
for sid,source in geo['sources'].items():lines += [f"- {sid} · [{source['title']}]({source['url']})：{source['notes']} 查阅：{source['checkedAt']}。"]
lines += ['','## 后续优先项','','秦良玉的南坪关、太平与播州旧寨，以及徐霞客的均州旧城，应结合方志和历史地图进一步核定。玄奘西行的未定年阶段不赋予猜测年份。','']
report='\n'.join(lines)
report_path=ROOT/'research/people/MAP_REVIEW.md'
if '--check' in sys.argv:
 assert report_path.read_text()==report, 'Regenerate map review report'
else:
 report_path.write_text(report)
