"""Publish biographies with separate, source-linked geographical reviews."""
import json
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.loads((ROOT/'research/people/initial-review.json').read_text())
geo=json.loads((ROOT/'research/people/map-review.json').read_text())
d['geography']=geo
# Only established regional reference coordinates are reused, never invented from an event's place text.
points={'长安':[108.94,34.26],'江阴':[120.28,31.92],'天台山一带':[121.03,29.15],'鸡足山':[100.37,25.96],'汴京':[114.31,34.8],'北京':[116.4,39.9],'东京':[139.69,35.68],'上海':[121.47,31.23],'绍兴':[120.58,30],'绍兴轩亭口':[120.58,30]}
# Record-level opt-in: no event locations, contested arrival dates, or unsupported birthplaces.
allowed={'xuanzang':{'xuanzang-003','xuanzang-005','xuanzang-008','xuanzang-014'},'xuxiake':{'xuxiake-001','xuxiake-003','xuxiake-008','xuxiake-010','xuxiake-011','xuxiake-012'},'liqingzhao':{'liqingzhao-002'},'qinliangyu':{'qinliangyu-007'},'qiujin':{'qiujin-002','qiujin-003','qiujin-005','qiujin-007','qiujin-008','qiujin-012'}}
record_ids={r['id'] for p in d['people'] for r in p['records']}
assert set(geo['records']).issubset(record_ids)
assert set(geo['withheld']).issubset(record_ids)
assert not set(geo['records']).intersection(geo['withheld'])
for p in d['people']:
 for r in p['records']:
  place='长安' if r['place'].startswith('长安') else r['place']
  r['displayXY']=points.get(place) if r['id'] in allowed[p['id']] else None
  r['locationReview']=None
  review=geo['records'].get(r['id'])
  if review:
   location=geo['places'][review['placeId']]
   r['displayXY']=location['xy']
   r['locationReview']={**review,**location}
  if r['id'] in geo['withheld']:
   assert not r['displayXY'], 'Withheld location cannot be mapped: '+r['id']
  r['mapNote']='地图标记沿用原型的城市或区域近似位置，尚未校准历史城址。' if r['displayXY'] else geo['withheld'].get(r['id'],'这条经历暂不标地图位置。')
  if review:
   r['mapNote']='地图标在'+location['name']+'。'+location['notes']
output=('// Generated by scripts/build_lives.py; research coordinates remain unchanged.\nconst LIVES_RESEARCH = '+json.dumps(d,ensure_ascii=False,separators=(',',':'))+';\n'+'''for(const life of LIVES_RESEARCH.people){
 const p=PEOPLE.find(p=>p.id===life.id);
 p.lifeResearch=life;p.audited=true;
 p.nodes=life.records.map(r=>({...r,xy:r.displayXY,text:r.narrative||r.evidence[0].supports,date:r.dateLabel,note:[r.dateLabel,r.limits,r.mapNote].filter(Boolean).join(' · ')}));
 p.caveat='每条经历都附有出处。日期有分歧的地方保留原说；地图只标出部分有到访依据的区域。';
}
''')
target=ROOT/'dist/lives-data.js'
if '--check' in sys.argv:
 assert target.read_text()==output, 'Run python3 scripts/build_lives.py to update website data'
else:
 target.write_text(output)
print('Published',sum(len(p['records']) for p in d['people']),'records and',sum(len(p['episodes']) for p in d['people']),'episodes;',sum(bool(r['displayXY']) for p in d['people'] for r in p['records']),'regional markers')

lines=['# 五人地图位置核验 · 2026-11-04','','本轮新增16条有到访依据的区域标记，覆盖12个地理参照区域；加上此前18条近似标记，网站共34条带位置的人生记录。其余76条年度经历及17段未定年经历仍以文字展示。没有把全部110条经历都称为已完成地理校准。','',geo['coordinatePolicy'],'','原先18条标记仍保留“沿用原型、历史城址尚未校准”的说明；本轮16条新增记录分别附到访依据、地名对应、坐标出处与精度说明。不同年份重复到同一区域，仍算不同人生记录。','','## 本轮新增','']
for person in d['people']:
 lines += ['### '+person['name'],'']
 for r in person['records']:
  g=r.get('locationReview')
  if not g:continue
  lines += [f"- **{r['id']} · {r['year']} · {r['title']}**：{g['name']}（{g['precision']}；经度、纬度 {g['xy']}）。",'  '+g['presenceBasis'],'  '+g['notes'],'  到访依据：'+ '；'.join(f"[{d['sources'][e['source']]['title']}]({d['sources'][e['source']]['url']}) · {e['locator']}" for e in r['evidence']),'  地理依据：'+'；'.join(f"[{geo['sources'][sid]['title']}]({geo['sources'][sid]['url']})" for sid in g['sources']),'']
lines += ['## 继续保留文字的记录','','这里只列本轮重点检查的限制；其余未列入本轮定位清单的经历沿用原有待核状态。','']
lines += [f'- {id}：{reason}' for id,reason in geo['withheld'].items()]
lines += ['','## 地理资料与使用范围','']
for sid,source in geo['sources'].items():lines += [f"- {sid} · [{source['title']}]({source['url']})：{source['notes']} 查阅：{source['checkedAt']}。"]
lines += ['','## 后续优先项','','秦良玉的石砫、南坪关与太平，以及徐霞客的均州旧城，应结合方志和历史地图进一步核定。玄奘西行的未定年阶段不赋予猜测年份。','']
report='\n'.join(lines)
report_path=ROOT/'research/people/MAP_REVIEW.md'
if '--check' in sys.argv:
 assert report_path.read_text()==report, 'Regenerate map review report'
else:
 report_path.write_text(report)
